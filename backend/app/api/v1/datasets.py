import io

from fastapi import APIRouter, Depends, File, Query, UploadFile
from fastapi.responses import StreamingResponse
from sqlalchemy import select
from sqlalchemy.orm import Session

from backend.app.config import ROOT, settings
from backend.app.core.exceptions import AppError
from backend.app.core.security import get_current_user, get_db
from backend.app.models import Dataset, User
from backend.app.schemas.api import CleanIn, SqlSourceIn
from backend.app.services import datasets as svc

router = APIRouter()


@router.post("", status_code=201)
async def upload(file: UploadFile = File(...), db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    limit = settings.max_upload_mb * 1024 * 1024
    content = await file.read(limit + 1)
    return svc.serialize(svc.ingest_upload(db, user, file.filename or "upload", content), detail=True)


@router.post("/from-sql", status_code=201)
def from_sql(body: SqlSourceIn, db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    return svc.serialize(svc.ingest_sql(db, user, body.url, body.query, body.table, body.name), detail=True)


@router.post("/load-sample", status_code=201)
def load_sample(db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    """Import the bundled demo sales dataset (generated by scripts/seed_demo_data.py)."""
    path = ROOT / "data" / "samples" / "sales.csv"
    if not path.exists():
        raise AppError("Sample data not found. Run: python scripts/seed_demo_data.py", 404)
    try:
        return svc.serialize(svc.ingest_upload(db, user, "sales_demo.csv", path.read_bytes()), detail=True)
    except AppError as e:
        if e.status_code == 409:
            existing = db.scalar(select(Dataset).where(Dataset.owner_id == user.id, Dataset.original_filename == "sales_demo.csv"))
            if existing:
                return svc.serialize(existing, detail=True)
        raise


@router.get("")
def list_datasets(db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    rows = db.scalars(select(Dataset).where(Dataset.owner_id == user.id).order_by(Dataset.created_at.desc())).all()
    return [svc.serialize(d) for d in rows]


@router.get("/{dataset_id}")
def get_one(dataset_id: int, db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    return svc.serialize(svc.get_dataset(db, user, dataset_id), detail=True)


@router.get("/{dataset_id}/preview")
def preview(dataset_id: int, limit: int = Query(50, ge=1, le=500), offset: int = Query(0, ge=0),
            db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    ds = svc.get_dataset(db, user, dataset_id)
    if ds.kind == "document":
        return {"kind": "document", "text": svc.load_text(ds)[:20_000]}
    return {"kind": "table", **svc.preview(ds, limit, offset)}


@router.post("/{dataset_id}/clean")
def clean(dataset_id: int, body: CleanIn, db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    ds = svc.get_dataset(db, user, dataset_id)
    result = svc.clean(db, user, ds, body.op, body.column, body.strategy)
    return {**result, "dataset": svc.serialize(ds, detail=True)}


@router.get("/{dataset_id}/download")
def download(dataset_id: int, db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    ds = svc.get_dataset(db, user, dataset_id)
    buf = io.StringIO()
    svc.load_df(ds).to_csv(buf, index=False)
    return StreamingResponse(iter([buf.getvalue()]), media_type="text/csv",
                             headers={"Content-Disposition": f'attachment; filename="{ds.table_name}.csv"'})


@router.delete("/{dataset_id}", status_code=204)
def delete(dataset_id: int, db: Session = Depends(get_db), user: User = Depends(get_current_user)):
    svc.delete(db, user, svc.get_dataset(db, user, dataset_id))
